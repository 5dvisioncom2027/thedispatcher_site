-- Старая схема: license_tier ('trial' | 'pro' | 'cloud'), где 'cloud'
-- исторически означало редакцию Premium клиента (отдельного 'premium' не
-- было вообще).
--
-- Новая схема добавляет 'base' и 'premium' как самостоятельные значения.
--
-- Живых пользователей в profiles пока нет (подтверждено владельцем проекта
-- 2026-11-24), поэтому отдельная миграция данных ('cloud' -> 'premium' для
